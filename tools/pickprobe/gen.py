# Generates the capability probes for the phone image fetcher and the build.cmd that builds
# them. See probe.cpp for the question being answered. Edit PROBES, run "python gen.py",
# then build.cmd. Each probe needs its own UID3 so they coexist on the phone.
import io

bs, q = chr(92), chr(34)

# The six capabilities a plain self-signed package can grant. Anything beyond these needs a
# certificate AND a rooted phone, which is why a probe limited to them is worth having.
USER = 'ReadUserData WriteUserData UserEnvironment NetworkServices LocalServices Location'

# (target, uid, caps, tag, needs_cert).
#
# ANSWER (measured on the phone, 2026-10-14): MGFetch needs **WriteDeviceData**. Nothing else.
# Symbigram declares it from v1.0.97 and is cert-signed with ../../cert/symbigram.cer.
#
# Full result table, each line a probe actually run on the device:
#   ReadUserData WriteUserData                           -> -46
#   Symbigram 1.0.96 (4 of the 6 self-signable caps)     -> -46
#   USER (all 6 self-signable caps)                      -> -46
#   USER + ReadDeviceData                                -> -46
#   USER + AllFiles                                      -> -46
#   USER + DRM                                           -> -46
#   USER + SwEvent                                       -> -46
#   USER + TrustedUI                                     -> -46
#   USER + WriteDeviceData                               -> gallery opens
#   USER + RDD WDD DRM AllFiles SwEvent TrustedUI        -> gallery opens
#   everything short of TCB                              -> gallery opens
#
# Keep any future capability list minimal: Symbian requires every DLL a process loads to be at
# least as privileged as that process, so surplus capabilities can break Qt plugin loading.
# The probes are kept so the same question can be re-answered on another firmware: edit PROBES,
# run "python gen.py", then build.cmd. Each probe needs its own UID3 to coexist on the phone.
PROBES = [
    ('PickWDD', '0xE4B1C2DE', USER + ' WriteDeviceData', 'wdd', True),
]


def pro(target, uid, caps, tag):
    L = [
        '# Symbigram - GPL-3.0-or-later. Capability probe for the Photos image fetcher.',
        '# Generated by gen.py; see probe.cpp for what is being narrowed down.',
        'TEMPLATE = app', 'TARGET = %s' % target, 'QT += core gui', 'SOURCES += probe.cpp',
        'DEFINES += PROBE_TAG=' + bs + q + tag + bs + q, '',
        'symbian {',
        '    TARGET.UID3 = %s' % uid,
        '    # Assigned, not appended: controlling this exactly is the point of the probe.',
        '    TARGET.CAPABILITY = %s' % caps,
        '    LIBS += -lmgfetch -lbafl',
        '    INCLUDEPATH += $$[QT_INSTALL_PREFIX]/epoc32/include/platform/mw',
        '    vendorinfo = ' + bs,
        '        ' + q + '%{' + bs + q + 'Symbigram' + bs + q + '}' + q + ' ' + bs,
        '        ' + q + ':' + bs + q + 'Symbigram' + bs + q + q,
        '    my_deployment.pkg_prerules = vendorinfo',
        '    DEPLOYMENT += my_deployment', '}']
    return '\n'.join(L) + '\n'


B = ['@echo off', 'rem Generated by gen.py - builds the narrowing probes.', 'setlocal',
     'call D:' + bs + 'QtSDK' + bs + 'Symbian' + bs + 'SDKs' + bs + 'SymbianSR1Qt474' + bs
     + 'env.bat', 'cd /d %~dp0', '']
for target, uid, caps, tag, cert in PROBES:
    io.open('%s.pro' % target.lower(), 'w', encoding='utf-8', newline='\r\n').write(
        pro(target, uid, caps, tag))
    B += ['echo === %s : %s' % (target, caps),
          'qmake %s.pro -spec symbian-sbsv2 CONFIG+=release' % target.lower(),
          'if errorlevel 1 exit /b 1',
          'call sbs -c arm.v5.urel.gcce4_4_1',
          'if errorlevel 1 exit /b 1']
    signing = (' ..' + bs + '..' + bs + 'cert' + bs + 'symbigram.cer ..' + bs + '..' + bs
               + 'cert' + bs + 'symbigram.key symbigram') if cert else ''
    B += ['call createpackage.bat %s_template.pkg release-armv5%s' % (target, signing),
          'if errorlevel 1 exit /b 1', '']
B += ['del /q *_unsigned.sis 2>nul', 'dir /b *.sis']
io.open('build.cmd', 'w', encoding='ascii', newline='\r\n').write('\n'.join(B) + '\n')
print('generated:', ', '.join(p[0] for p in PROBES))
