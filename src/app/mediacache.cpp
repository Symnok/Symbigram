QByteArray MediaCache::expandStrippedThumb(const QByteArray &stripped)
{
    // A stripped thumbnail is at least 3 bytes: a marker (0x01) and the width and height
    // that patch bytes 164 and 166 of the header.
    if (stripped.size() < 3 || uchar(stripped.at(0)) != 0x01) return QByteArray();
    QByteArray header(reinterpret_cast<const char *>(JpegHeader), int(sizeof(JpegHeader)));
    header[164] = stripped.at(1);
    header[166] = stripped.at(2);
    return header + stripped.mid(3) + QByteArray(reinterpret_cast<const char *>(JpegFooter), int(sizeof(JpegFooter)));
}

QString MediaCache::strippedThumbFile(const TgMedia &media)
{
    if (media.strippedThumb.size() < 3) return QString();
    QString path = pathForKey(keyFor(media, QLatin1String("stripped")), QLatin1String("jpg"));
    if (QFile::exists(path)) return path;
    QByteArray jpeg = expandStrippedThumb(media.strippedThumb);
    if (jpeg.isEmpty()) return QString();
    QFile f(path);
    if (!f.open(QIODevice::WriteOnly)) return QString();
    f.write(jpeg);
    f.close();
    return path;
}
